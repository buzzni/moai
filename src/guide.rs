        // `<크기>KB` 는 자리 표시라 수가 없다 — 그것만 건너뛰고 적힌 수는 모두 잰다.
        let stated = |text: &str| -> Vec<String> {
            text.match_indices("KB")
                .map(|(at, _)| {
                    let head = &text[..at];
                    head[head.trim_end_matches(|c: char| c.is_ascii_digit()).len()..].to_string()
                })
                .filter(|digits| !digits.is_empty())
                .collect()
        };
